/**
 * @file    bsp_flash_pad.c
 * @brief   Flash 烧录 8 字节对齐尾填充 —— 解决 dslite 烧录工具的对齐硬约束
 *
 * ============================================================
 * 这个文件是做什么的？（写给初学者）
 * ============================================================
 * 这是一个只有 3 行有效代码的文件，但它解决了一个"不解决就烧录失败"的问题。
 *
 * 问题背景：
 *   MSPM0G3507 的 Flash 控制器每次只能写 64 位（8 字节）。
 *   烧录工具（dslite）在烧录前会检查你的程序文件大小是否是 8 的倍数。
 *   如果不是，烧录工具直接报错拒绝烧录：
 *     "Length of block is N, but it should be divisible by 8"
 *
 * 为什么会出现不是 8 的倍数？
 *   编译链接后，你的程序可能有 12588 字节之类的"不规则大小"。
 *   这是因为代码和数据的排列组合很难恰好凑满 8 字节边界。
 *
 * 怎么解决？
 *   在程序末尾加一段"填充数据"（pad），把总大小凑到 8 的倍数。
 *   但这个填充数据的放置位置非常讲究——
 *   需要通过 scatter 文件精确控制链接器，确保填充总是放在
 *   所有代码的"最后面"。
 *
 * ============================================================
 * 这个文件为什么必须单独成一个 .c 文件？
 * ============================================================
 * 因为 scatter 文件（mspm0g3507.sct）中需要用到模块级的 selector：
 *
 *   bsp_flash_pad.o (.flash_pad, +Last)
 *
 * 这行指令的含义是：
 *   "把 bsp_flash_pad.o 中的 .flash_pad 段放在所有段的最后面"
 *
 * 如果把这个变量放在其他 .c 文件里（比如 main.c），
 * 链接器可能不会把它放到最后——因为 ARMCLANG 链接器的".ANY 通配规则"
 * 可能抢在 +Last 规则之前就把段分配掉了。
 *
 * 实测证明：模块级 selector（指定具体 .o 文件）的优先级高于 .ANY 通配符。
 * 这是唯一能稳定保证"闪存填充放在末尾"的写法。
 *
 * ============================================================
 * 为什么填充值 0xFFFFFFFFFFFFFFFF？
 * ============================================================
 * Flash 的"擦除态"就是全 1（0xFF）。写 0xFF 到 Flash 等同于"不操作"——
 * 不会产生实际的写功耗，也不占用真实的写入寿命。
 * 这个 8 字节只是"占位"，让 PT_LOAD 段变成 8 的倍数。
 *
 * ============================================================
 * 编译属性详解
 * ============================================================
 *   __attribute__((used, section(".flash_pad"), aligned(8)))
 *
 *   used：
 *     告诉编译器："这个变量虽然看起来没人用，但不要删掉它"。
 *     因为 ARMCLANG 的 -O2 优化可能会"死代码消除"（dead-strip）——
 *     把"看起来没有被引用"的变量/函数删掉。
 *     如果不加 used，即使 scatter 文件指定了 section，
 *     链接器也可能因为"该 .o 没有可见符号"而丢弃整个文件。
 *
 *   section(".flash_pad")：
 *     告诉编译器："把这个变量放在 .flash_pad 这个自定义段里"。
 *     scatter 文件中的 `bsp_flash_pad.o (.flash_pad, +Last)`
 *     就是通过这个 section 名字找到它的。
 *
 *   aligned(8)：
 *     告诉编译器/链接器："这个变量必须放在 8 字节对齐的地址上"。
 *     保证 _flash_image_pad 的起始地址是 8 的倍数，
 *     配合 +Last 位置，最终程序的末尾也落在 8 字节边界上。
 *
 *   const：
 *     这个变量是"只读"的，编译器会把它放在 Flash（ROM）区域，
 *     而不是 RAM 区域。我们不希望这个填充数据占用宝贵的 RAM。
 */

/* 引入 uint64_t 类型（64 位无符号整数，正好 8 字节） */
#include <stdint.h>

/**
 * _flash_image_pad：Flash 镜像的 8 字节尾填充
 *
 * 这个变量存在的唯一目的，就是让整个程序的 Flash 镜像大小
 * 变成 8 字节的倍数，满足 dslite 烧录工具的硬约束。
 *
 * 它被放在特殊的 .flash_pad 段中，
 * 由 scatter 文件的 `bsp_flash_pad.o (.flash_pad, +Last)` 指令
 * 强制放在所有代码的最末尾。
 *
 * 填充值：0xFFFFFFFFFFFFFFFF（8 个 0xFF）
 *   与 Flash 擦除态一致，写入时等同于"不操作"，不消耗写入寿命。
 *
 * 类型选择：uint64_t（正好 8 字节）
 *   配合 aligned(8) 属性，保证这一段本身大小 = 8 字节、起始地址也对齐到 8。
 *   由于这是最后一段，程序总大小 = 之前的大小（可能不齐）+ 这个 8 字节
 *   → 总大小必然对齐到 8（多写入 0~7 字节填充）。
 */
__attribute__((used, section(".flash_pad"), aligned(8)))
const uint64_t _flash_image_pad = 0xFFFFFFFFFFFFFFFFULL;
