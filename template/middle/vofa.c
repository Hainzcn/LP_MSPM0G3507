/**
 * @file    vofa.c
 * @brief   VOFA+ JustFloat 协议打包器的实现
 *
 * ============================================================
 * 这个文件是做什么的？（写给初学者）
 * ============================================================
 * 你已经在 vofa.h 中知道 VOFA+ 是做什么的了（把 float 数据发到电脑上画波形）。
 * 这个 vofa.c 就是"具体怎么打包"的代码实现。
 *
 * 如果把 vofa.h 比作"菜单"（告诉我有什么菜），
 * 那 vofa.c 就是"后厨"（具体怎么做菜）。
 *
 * 这个文件非常短——只有 32 行有效代码。
 * 但它包含了几个重要的嵌入式设计思想：
 *   1. 防御性编程：所有可能的错误输入都被检查
 *   2. 栈上缓冲区：不使用 malloc，适合单片机环境
 *   3. memcpy 批量拷贝：比逐字节赋值更高效
 *   4. 函数指针解耦：不依赖具体的 UART 硬件
 */

/* ============================================================
 * 头文件包含
 * ============================================================
 * #include "vofa.h"：引入 vofa.h 中定义的类型和函数声明。
 *   这是 C 语言模块化的标准做法——头文件放"声明"（有什么），
 *   源文件放"实现"（怎么做）。
 *
 * #include <string.h>：引入 memcpy 函数的声明。
 *   memcpy 是 C 标准库中的"内存拷贝"函数。
 *   为什么用 memcpy 而不是 for 循环？
 *   1. 简洁——一行代码代替一个循环
 *   2. 高效——编译器通常把 memcpy 优化为高效的块拷贝指令
 *      （如 ARM 的 LDM/STM 指令，一次加载/存储多个寄存器）
 *   在 Keil MDK 中，memcpy 可能被替换为 __aeabi_memcpy，
 *   其性能通常优于手写 for 循环。
 */
#include "vofa.h"
#include <string.h>      /* 使用 memcpy 函数 */

/* ============================================================
 * 宏定义
 * ============================================================
 * #define VOFA_MAX_CHANNELS  32u
 *
 * 这个宏定义了 VOFA+ 一次最多能发送多少个 float 数据（通道数）。
 * 32 是从哪里来的？——这个值决定了栈上缓冲区的大小。
 *
 * 缓冲区大小 = 32 × 4（每个 float 4 字节）+ 4（帧尾 4 字节）= 132 字节。
 * 为什么选 32？
 *   1. 够用：自平衡小车一般只需要 3~6 个通道（pitch/rate/output/电压等）
 *   2. 安全：132 字节在栈上分配非常安全（MSPM0G3507 栈通常有 1~4 KB）
 *   3. 有扩展余量：即使将来需要 20 个通道，132 字节也完全装得下
 *
 * 为什么不设得更大（比如 64）？
 *   如果设 64，缓冲区 = 64×4 + 4 = 260 字节，在 1 KB 的栈上占了 25%。
 *   还要考虑函数调用链中其他函数的栈需求——我们的目标是用够用、不浪费。
 */
#define VOFA_MAX_CHANNELS  32u

/* ============================================================
 * 静态常量：JustFloat 协议的帧尾标记
 * ============================================================
 * static：只在当前文件（vofa.c）中可见，其他 .c 文件不能访问。
 * const：内容不可修改——这 4 个字节是固定的。
 * 放在 Flash（ROM）中，不消耗宝贵的 RAM。
 *
 * 这 4 个字节 0x00 0x00 0x80 0x7F 是 IEEE 754 浮点数
 * "+infinity"（正无穷）的小端字节序表示。
 *
 * +infinity 的 IEEE 754 二进制：
 *   符号位(S) = 0
 *   指数位    = 11111111 (全1)
 *   尾数位    = 000...000 (全0)
 *   = 0x7F800000（大端序）
 *
 * 小端存储（低地址存低字节）：
 *   0x7F800000 → [0x00, 0x00, 0x80, 0x7F]
 *
 * 为什么用正无穷做帧尾？
 *   正常的 float 数据不可能等于 +infinity，
 *   所以 VOFA+ 看到这 4 个字节就知道"一帧结束了"。
 *   这叫做"哨兵值"（sentinel value）——用一个不可能出现在
 *   正常数据中的特殊值来标记边界。
 */
static const uint8_t JUSTFLOAT_TAIL[4] = { 0x00u, 0x00u, 0x80u, 0x7Fu };

/* ============================================================
 * 静态变量：注册的底层写函数指针
 * ============================================================
 * static：只在当前文件可见。
 *
 * s_writer 是一个"函数指针"——它存储了一个函数的地址。
 * 当我们调用 s_writer(buf, len) 时，实际调用的是之前通过
 * vofa_set_writer() 注册的那个函数。
 *
 * 初始值为 NULL（空指针）：
 *   这是一个安全设计——如果调用方忘记了 vofa_set_writer()，
 *   s_writer 就是 NULL。在 vofa_send() 中会检查 s_writer == NULL
 *   然后直接返回，不会调用地址 0（那会导致程序崩溃）。
 *
 * 变量命名惯例：
 *   s_ 前缀表示 "static"——提醒这个变量是模块内部的。
 */
static vofa_writer_fn s_writer = NULL;

/* ============================================================
 * 公开 API 函数
 * ============================================================ */

/**
 * @brief  注册底层字节写函数
 *
 * 功能：把外部传入的写函数地址保存到 s_writer 中，
 *       供 vofa_send() 发送数据时调用。
 *
 * 这是"依赖注入"（Dependency Injection）模式的体现：
 *   - 传统做法：vofa.c 直接调用某个 UART 发送函数
 *   - 依赖注入：vofa.c 通过函数指针调用，具体函数由外部注入
 *
 * 依赖注入的好处：
 *   1. 解耦：vofa.c 不需要知道用的是哪个 UART（USB/蓝牙/虚拟串口）
 *   2. 灵活：运行时可以通过再次调用 vofa_set_writer() 切换输出路径
 *   3. 可测试：可以注入一个"假发送函数"来验证 vofa_send() 的行为
 *
 * 调用示例：
 * @code
 *   // 在 main() 初始化中注册
 *   vofa_set_writer(bsp_log_uart_send_bytes);
 *
 *   // 之后所有 vofa_send() 的数据都会通过日志串口发送
 * @endcode
 *
 * 注意：
 *   - 这个函数可以在运行时多次调用，随时切换 writer
 *   - 传 NULL 可以"取消注册"——之后 vofa_send() 会静默返回
 *   - 必须在第一次调用 vofa_send() 之前至少调用一次（非 NULL）
 *
 * @param writer  指向底层字节写函数的函数指针
 *                符合 vofa_writer_fn 类型签名的函数都可以传入
 *                （参数：const uint8_t* data, size_t len；返回值：void）
 */
void vofa_set_writer(vofa_writer_fn writer)
{
    /* 把传入的 writer 函数地址保存到静态变量 s_writer 中。
     * 之后每次 vofa_send() 调用时，都会通过 s_writer 来发送数据。
     * 
     * 注意：这里没有 NULL 检查——允许传 NULL 来表示"取消注册"。
     * vofa_send() 中有 s_writer == NULL 的检查，会安全地不做任何操作。 */
    s_writer = writer;
}

/**
 * @brief  打包并发送 N 个 float 数据到 VOFA+ 上位机（核心函数）
 *
 * 功能：按照 JustFloat 协议，把 N 个 float 打包成二进制流，
 *       通过之前注册的 writer 函数发送出去。
 *
 * 这就是整个 VOFA+ 模块唯一的核心"干活"函数。
 * 每次调用它，都会：
 *   1. 在栈上准备一个缓冲区
 *   2. 把 float 数据拷贝到缓冲区
 *   3. 追加 4 字节帧尾标记
 *   4. 调用注册的 writer 一次性发出去
 *
 * 调用方式（典型用法）：
 * @code
 *   float data[] = { pitch, rate, output };
 *   vofa_send(data, 3);  // 发送 3 个通道
 * @endcode
 *
 * 协议打包格式（以 n=3 为例）：
 *   偏移 0~11：3 个 float 的 IEEE 754 二进制表示（小端）
 *              每个 float 占 4 字节，共 12 字节
 *   偏移 12~15：帧尾 0x00 0x00 0x80 0x7F
 *   总共：16 字节
 *
 * 安全性检查（共 4 个条件，见下方代码注释）：
 *   1. s_writer == NULL：忘记注册 writer → 静默返回
 *   2. ch == NULL：传入了空指针 → 静默返回
 *   3. n == 0：没有数据要发 → 静默返回
 *   4. n > 32：通道数超限 → 静默返回
 *
 * 为什么使用栈上固定大小的缓冲区而不是动态分配？
 *   嵌入式系统中禁止使用 malloc（动态内存分配），原因：
 *   1. 内存碎片：反复分配释放会产生无法利用的小碎片
 *   2. 不可靠：malloc 可能返回 NULL（内存不足）
 *   3. 不确定性：malloc 的执行时间不确定，影响实时性
 *   4. 栈上分配是确定的、快速的——只是移动栈指针
 *
 * 为什么不逐个 float 发送（减少缓冲区大小）？
 *   每次 writer 调用都涉及中断处理（UART 发送中断）。
 *   如果分 3 次发送（每次一个 float + 帧尾），会产生 3 次中断。
 *   一次性发出全部数据，只需要 1 次中断——更高效。
 *
 * @param ch  待发送的浮点数据数组指针
 *            数组中的每个 float 对应 VOFA+ 上的一个通道
 *            数据必须是有效的（不能为 NULL，必须有 n 个 float）
 *
 * @param n   通道数（= 要发送的 float 个数）
 *            有效范围：1 ~ 32
 *            如果传 0，函数直接返回，不发送任何数据
 *            如果传 > 32，函数直接返回，不发送任何数据
 */
void vofa_send(const float *ch, uint8_t n)
{
    /* ================================================================
     * 安全检查：合法条件检查
     * ================================================================
     * 以下两个条件导致函数立即返回，不执行任何操作。
     *
     * 条件 1：s_writer == NULL || ch == NULL
     *   - s_writer == NULL：调用方忘记注册 writer，没有输出目标
     *   - ch == NULL：调用方传入了空指针，没有有效数据
     *   这两个条件只要有一个成立，就没法做任何有用的事。
     *
     * 条件 2：n == 0u || n > VOFA_MAX_CHANNELS
     *   - n == 0：没有通道要发送，做了也是白做
     *   - n > VOFA_MAX_CHANNELS：通道数超限，后续 memcpy 会写越界
     *   注意这里用条件 2 写在条件 1 之后——因为条件 2 的检查需要
     *   确保 (ch != NULL) 的情况下才能访问 ch 中的数据。
     *   但 n 检查不涉及解引用 ch，所以放在一起也没问题。
     */
    if (s_writer == NULL || ch == NULL) { return; }
    if (n == 0u || n > VOFA_MAX_CHANNELS) { return; }

    /* ================================================================
     * 申请栈上缓冲区
     * ================================================================
     * 在栈上分配一个固定大小的缓冲区，用于存放打包好的数据。
     *
     * 缓冲区大小 = VOFA_MAX_CHANNELS × 4 + 4
     *             = 32 × 4 + 4
     *             = 132 字节
     *
     * 这个缓冲区分配在"栈"（stack）上，而不是"堆"（heap）上。
     * 栈上分配的特点是：
     *   - 非常快：只是移动栈指针（SP 寄存器），一条指令
     *   - 自动释放：函数返回时栈指针自动恢复，无需手动 free
     *   - 大小固定：不能在运行时改变
     *
     * 虽然我们不需要 132 字节的全部（n 可能只有 3，只需要 16 字节），
     * 但用固定大小的缓冲区避免了"变长数组"（VLA，Variable Length Array）
     * 的使用。VLA 在 C99 中是标准特性，但在嵌入式编译器中支持不一，
     * 且可能导致栈溢出（如果 n 意外变得很大）。
     * 固定大小更安全、更可预测。
     */
    uint8_t buf[VOFA_MAX_CHANNELS * 4u + 4u];

    /* ================================================================
     * 计算有效数据长度
     * ================================================================
     * payload_bytes = n × sizeof(float)
     * sizeof(float) = 4（IEEE 754 单精度浮点数）
     *
     * (size_t)n：把 uint8_t 提升为 size_t（无符号整数类型），
     * 目的是让乘法在更宽的类型上进行，避免 uint8_t 溢出的可能性。
     * 虽然 n 最大 32，32 × 4 = 128 < 255（uint8_t 最大值），
     * 但这是一个好习惯——"提升到更宽类型再做运算"。
     */
    size_t  payload_bytes = (size_t)n * sizeof(float);

    /* ================================================================
     * 拷贝 float 数据到缓冲区
     * ================================================================
     * memcpy(dest, src, count)：从 src 拷贝 count 个字节到 dest。
     *
     * 这里把 ch 指向的 n 个 float（共 payload_bytes 字节）
     * 原样拷贝到 buf 的开头。
     *
     * 为什么不直接使用 ch 中的数据（减少一次拷贝）？
     *   因为后面还要追加帧尾。帧尾需要紧跟在 float 数据后面，
     *   所以必须把数据集中到一个连续的缓冲区中。
     *
     * 为什么用 memcpy 而不是 for 循环？
     *   1. 简洁——一行代替一个循环
     *   2. 高效——编译器通常会把 memcpy 优化为高效的块拷贝指令
     *      对于 12~132 字节的小数据量，优化效果明显
     */
    memcpy(buf, ch, payload_bytes);

    /* ================================================================
     * 拷贝帧尾到缓冲区末尾
     * ================================================================
     * &buf[payload_bytes] 是指向"float 数据末尾"的指针。
     * 例如 n=3 时，payload_bytes=12，buf[12] 是第 13 个字节。
     * 帧尾就从 buf[12] 开始存放，占 buf[12]~buf[15]。
     *
     * 这样就构成了完整的 JustFloat 帧：
     *   buf[0..11]  = 3 个 float 的二进制数据
     *   buf[12..15] = 帧尾 0x00 0x00 0x80 0x7F
     *
     * 两次 memcpy 也可以合成一次——先 memcpy float 数据，
     * 再 memcpy 帧尾。分开写更清晰，而且编译器会进行优化。
     */
    memcpy(&buf[payload_bytes], JUSTFLOAT_TAIL, 4u);

    /* ================================================================
     * 通过注册的 writer 一次性发送
     * ================================================================
     * s_writer(buf, payload_bytes + 4u)：
     *   - buf：打包好的数据缓冲区
     *   - payload_bytes + 4u：总长度 = float 数据 + 帧尾
     *
     * 例如 n=3 时：12 + 4 = 16 字节
     *
     * 这里是"一次性发送"——在整个 buf 准备好之后，一次 writer 调用
     * 发送所有数据。这样做的好处：
     *   1. 减少中断次数（串口发送中断）
     *   2. 保持帧的原子性（不会被其他输出打断）
     *   3. 减少函数调用开销
     *
     * 注意：此时 s_writer 已经不可能是 NULL（已在函数开头检查过）。
     */
    s_writer(buf, payload_bytes + 4u);
}
