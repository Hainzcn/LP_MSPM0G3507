/**
 * @file    pid.c
 * @brief   通用浮点 PID 控制器 —— 位置式 + 抗积分饱和 + 微分项独立滤波 的实现
 *
 * ============================================================
 * 这个文件是做什么的？（写给初学者）
 * ============================================================
 * pid.h 中声明了 PID 控制器的"接口"——有什么函数、怎么调用。
 * 而这个 pid.c 是"实现"——这些函数具体是怎么工作的。
 *
 * 如果把 PID 控制器比作一台自动调节机器，那么：
 *   pid.h = 机器的操作面板（有按钮、旋钮、仪表盘）
 *   pid.c = 机器内部的齿轮、弹簧、电路（具体工作原理）
 *
 * 你需要先读 pid.h（知道怎么用），再读 pid.c（知道为什么）。
 *
 * ============================================================
 * 文件内容一览
 * ============================================================
 * 1. clampf() —— 浮点数限幅工具（见名知意：clamp = 夹紧）
 * 2. pid_init() —— 初始化为安全默认值（Kp=Ki=Kd=0，输出为 0）
 * 3. pid_set_gains() —— 设置三个增益系数
 * 4. pid_set_output_limit() —— 设置输出范围
 * 5. pid_set_integral_limit() —— 设置积分上限（抗饱和）
 * 6. pid_set_d_filter() —— 设置微分滤波系数
 * 7. pid_reset() —— 清空内部状态
 * 8. pid_step() ⭐ —— 核心！每拍执行一次 PID 计算
 */

/* ============================================================
 * 头文件包含
 * ============================================================
 * #include "pid.h"：引入自己配套的头文件，里面定义了 pid_t 结构体
 *   和所有函数的声明。这是 C 语言模块化的标准做法——
 *   头文件放"声明"（告诉编译器有什么），源文件放"定义"（具体怎么做）。
 *
 * #include <stddef.h>：引入标准库的 NULL 宏定义。
 *   NULL 在 C 语言中就是 (void*)0，表示"空指针"。
 *   注意：其实 pid.h 已经通过 <stdbool.h> 间接包含了一些内容，
 *   但 <stddef.h> 需要显式包含以确保 NULL 可用。
 *   不过在很多编译器中，不加这行也能编译通过（因为别的头文件可能已经
 *   包含了它）。加这行是"显式依赖"的好习惯。
 */
#include "pid.h"
#include <stddef.h>

/* ============================================================
 * 内部辅助函数
 * ============================================================
 * 这里的函数用 static 修饰，表示只在本文件内部使用。
 * 外部代码无法调用它们——这是封装（encapsulation）的体现：
 * 内部的实现细节对外部隐藏，外部只需关心公开 API。
 */

/**
 * @brief  clampf —— 浮点数限幅（夹紧）
 *
 * 功能：把浮点数 v 强制限制在 [lo, hi] 范围内。
 *   - 如果 v < lo → 返回 lo（低于下限→按下限走）
 *   - 如果 v > hi → 返回 hi（高于上限→按上限走）
 *   - 否则 → 返回 v 本身（在范围内→不变）
 *
 * 为什么需要这个函数？
 *   PID 控制中到处都要做"限幅"：
 *   1. 积分项要限幅（防止积分饱和）
 *   2. 输出要限幅（防止超出物理范围，如电机 PWM 最大值）
 *   3. 滤波系数要限幅（alpha 必须在 [0, 1] 之间）
 *
 * 如果没有限幅，会发生什么？
 *   积分项可能累积到几百万（int 都存不下），
 *   或者输出值远超电机的承受范围。
 *
 * 实现方式：三个 if 判断
 *   为什么不用 fminf/fmaxf 库函数？
 *   为了减少对外部数学库的依赖。在嵌入式系统中，
 *   标准库可能不完整，自己写一个简单的 clamp 更可靠。
 *   而且这个函数会被编译器内联优化，性能损耗忽略不计。
 *
 * @param v  要限制的数值
 * @param lo 下限（最小值）
 * @param hi 上限（最大值），必须 lo < hi，否则行为取决于比较结果
 * @return float  限制后的数值，范围 [lo, hi]
 */
static float clampf(float v, float lo, float hi)
{
    /* 三路比较：
     *   第一路：低于下限 → 返回下限
     *   第二路：高于上限 → 返回上限
     *   第三路：都没触发 → 返回原值
     * 注意这三个 return 是互斥的——最多只有一个会执行。
     * 因为 if (v < lo) 和 if (v > hi) 不可能同时成立
     * （一个数不可能既小于 lo 又大于 hi，除非 lo > hi 传参错误）。 */
    if (v < lo) return lo;   /* 低于下限：按下限走 */
    if (v > hi) return hi;   /* 高于上限：按上限走 */
    return v;                /* 在范围内：保持不变 */
    /* 知识点：if 没有 else 也能工作
     * 因为前两个 if 都有 return，执行到第三个 return 时，
     * 必然已经排除了 v < lo 和 v > hi 两种情况。
     * 这是 C 语言中常见的"提前返回"模式，可以少写几个 else。 */
}

/* ============================================================
 * 公开 API —— 配置函数
 * ============================================================
 * 下面这几个函数（pid_init ~ pid_reset）的作用是"配置"PID 控制器。
 * 它们不执行控制计算（不产生控制量），只是告诉 PID 控制器：
 *   - 你的增益是多少（Kp/Ki/Kd）
 *   - 你的输出范围是多少
 *   - 你的积分上限是多少
 *   - 你的滤波系数是多少
 *
 * 这些函数通常在初始化阶段调用（上电时调用一次），
 * 或者在调试阶段调整参数时调用。
 */

/**
 * @brief  初始化 PID 控制器为安全默认值
 *
 * 这是 PID 控制器的"构造函数"——在使用之前必须调用一次。
 * 它把所有字段设为安全初始值，确保：
 *   1. 增益全为 0 → 输出永远为 0 → 电机不动 → 安全
 *   2. 输出限幅为 ±1000（千分比默认量纲）
 *   3. 内部状态全部清零（没有"历史残留"）
 *
 * 调用示例：
 * @code
 *   pid_t balance_pid;          // 定义 PID 实例（栈上分配）
 *   pid_init(&balance_pid);     // 设为默认值
 *   // 然后再调用 pid_set_gains() 设置实际增益
 * @endcode
 *
 * 为什么增益默认是 0 而不是某个"经验值"？
 *   初学者可能会觉得："设个经验值不是更方便吗？少调一步。"
 *   但每个机械系统（重量、电机、重心）都不同，经验值没意义。
 *   而且如果忘记调参，增益为 0 → 输出为 0 → 安全。
 *   如果增益是别的值，忘记调参会造成不可预测的行为。
 *   这就是"安全设计"——宁可不动，不能乱动。
 *
 * 初始化后的状态一览：
 *   ┌──────────────┬───────────┬──────────────────────────┐
 *   │ 字段         │ 默认值    │ 说明                     │
 *   ├──────────────┼───────────┼──────────────────────────┤
 *   │ kp, ki, kd   │ 0         │ 输出为 0，安全           │
 *   │ u_min, u_max │ ±1000     │ 千分比量纲               │
 *   │ i_max        │ 0         │ 自动跟随 u_max           │
 *   │ d_filter     │ 0         │ 禁用滤波                 │
 *   │ i_term       │ 0         │ 无积分累积               │
 *   │ prev_meas    │ 0         │ 无历史测量值             │
 *   │ has_prev     │ false     │ 第一拍标志               │
 *   └──────────────┴───────────┴──────────────────────────┘
 *
 * @param pid  指向 pid_t 结构体的指针（不能为 NULL）
 *             如果为 NULL，函数直接返回不做任何事
 */
void pid_init(pid_t *pid)
{
    /* ---- 防御性编程 ---- */
    /* 检查传入指针是否为 NULL。
     * 如果调用方不小心传了 NULL（比如忘记取地址 &），
     * 后面的 pid->kp = 0.0f 会试图写入地址 0，
     * 这在嵌入式系统中会触发硬件异常（HardFault），导致程序死机。
     * 这个检查就防止了这种情况。 */
    if (pid == NULL) return;

    /* ---- 增益全为 0：安全默认值 ---- */
    /* 调用方必须显式调用 pid_set_gains() 才有输出。
     * 这个设计比"偷偷设个魔法数字"要安全得多。 */
    pid->kp = 0.0f;   /* 比例增益：0 → P 项无输出 */
    pid->ki = 0.0f;   /* 积分增益：0 → I 项无输出 */
    pid->kd = 0.0f;   /* 微分增益：0 → D 项无输出 */

    /* ---- 输出限幅：±1000 千分比 ---- */
    /* 为什么是 1000 而不是 255 或 65535？
     *   1000 是"千分比"（permille）量纲，1000 = 100% = 满输出。
     *   100 是百分比，但千分比精度更高（可以精确到 0.1%）。
     *   这个量纲对电机控制很直观：输出 500 → 50% 出力。
     *   如果实际电机的 PWM 范围不同（如 8 位 PWM 的 0~255），
     *   调用方需要自己映射或修改限幅值。 */
    pid->u_min = -1000.0f;  /* 输出下限：-1000（反向满出力） */
    pid->u_max =  1000.0f;  /* 输出上限：+1000（正向满出力） */

    /* ---- 积分限幅：0 = 跟随 u_max ---- */
    /* i_max = 0 是一个"特殊值"：
     *   在 pid_step() 中，如果 i_max == 0，实际积分上限被设为 u_max。
     *   这样设计的好处是：对于大多数用户，不需要单独设置积分限幅，
     *   输出限幅自然就成了积分的上限。
     *   但如果想更严格地限制积分（积分上限 < 输出上限），
     *   可以调用 pid_set_integral_limit() 设置具体值。 */
    pid->i_max = 0.0f;

    /* ---- 微分滤波：禁用 ---- */
    /* d_filter_alpha = 0 表示"禁用 EMA 滤波"。
     * 微分项直接使用原始测量值求导，不做平滑处理。
     * 如果传感器噪声较大（比如 MPU6050 的原始数据），
     * 建议开启滤波（alpha = 0.1 ~ 0.3）。
     * 如果传感器数据本身已经做了滤波（如 MS901M 内部已处理），
     * 可以保持禁用。 */
    pid->d_filter_alpha = 0.0f;

    /* ---- 内部状态全部清零 ---- */
    /* 这些"历史状态"记录了 PID 之前的运行情况。
     * 清零意味着"从零开始，没有历史包袱"。 */
    pid->i_term       = 0.0f;  /* 积分累积值归零 */
    pid->prev_meas    = 0.0f;  /* 上一拍测量值归零 */
    pid->prev_d_filt  = 0.0f;  /* 上一拍微分滤波值归零 */
    pid->has_prev     = false; /* 首拍标志：true=有历史，false=无历史 */
}

/**
 * @brief  设置 PID 的三个增益系数
 *
 * 这是 PID 控制器最重要的配置函数——三个增益直接决定了控制效果。
 *
 * 增益的物理意义：
 *   Kp（比例）：对"当前误差"的反应强度
 *     比喻：推门的时候，门卡住了你使多大劲——越卡越使劲
 *   Ki（积分）：对"累积误差"的反应强度
 *     比喻：门一直推不开，你就越推越用力
 *   Kd（微分）：对"误差变化趋势"的反应强度
 *     比喻：感觉到门开始动了，你就提前收力防止撞墙
 *
 * 调参顺序建议："先 P，再 D，最后 I"
 *   1. Kp 从 0 慢慢增加，直到系统开始轻微震荡
 *      → 此时系统能回正，但会来回晃
 *   2. Kd 从 0 慢慢增加，直到震荡被抑制
 *      → 此时系统稳定，但可能有"静差"（差一点点到目标）
 *   3. Ki 从 0 慢慢增加，消除静差
 *      → 此时系统稳定且精确
 *
 * 参数可以是任意非数值（正数、负数、小数），调用方自己负责。
 * 但大多数控制系统中，Kp/Ki/Kd 都是正数。
 * 如果设成负数，控制器会"反向工作"——误差越大，反方向出力越大。
 *
 * @param pid  PID 实例指针
 * @param kp  比例增益（Proportional Gain）
 * @param ki  积分增益（Integral Gain）
 * @param kd  微分增益（Derivative Gain）
 */
void pid_set_gains(pid_t *pid, float kp, float ki, float kd)
{
    /* NULL 检查：防止传入空指针 */
    if (pid == NULL) return;

    /* 赋值：简单粗暴，把传入值直接写入结构体
     * 没有校验？对——Kp 可以是负数，可以是 0，可以是 1e6。
     * 因为这个函数只负责"设置"，不负责"判断是否合理"。
     * 合理不合理是调用方的事。这是 C 语言中常见的"信任调用方"的设计哲学。 */
    pid->kp = kp;   /* 设置比例增益 */
    pid->ki = ki;   /* 设置积分增益 */
    pid->kd = kd;   /* 设置微分增益 */
}

/**
 * @brief  设置输出限幅 [lo, hi]
 *
 * 把 PID 输出限制在 [lo, hi] 之间。
 * 任何超出这个范围的输出都会被"钳位"到边界值。
 *
 * 为什么需要输出限幅？
 *   电机 PWM 有最大值（比如 1000），舵机有最大转角。
 *   如果不限幅，PID 可能输出 2000，但电机只能接受 1000——
 *   多余的能量无处消耗，可能损坏驱动器。
 *
 * @param pid  PID 实例指针
 * @param lo   输出下限（最小值）
 * @param hi   输出上限（最大值）
 *
 * 注意：如果 lo >= hi，函数忽略此次设置（保持原有值）。
 * 因为 lo >= hi 意味着"下限 >= 上限"，这是一个无效设置。
 * 比如 pid_set_output_limit(&pid, 500, -500) 会被忽略。
 */
void pid_set_output_limit(pid_t *pid, float lo, float hi)
{
    if (pid == NULL) return;     /* NULL 检查 */

    /* 有效性检查：下限必须小于上限
     * 如果 lo >= hi：
     *   1. lo=100, hi=50：下限比上限高，不合理
     *   2. lo=100, hi=100：下限等于上限，输出被"钉死"在一个值
     * 这两种情况都不能用，直接 return 忽略设置。
     * 注意：用 >= 而不是 >，因为 lo == hi 也被认为无效。 */
    if (lo >= hi) return;

    /* 设置上下限 */
    pid->u_min = lo;   /* 下限 */
    pid->u_max = hi;   /* 上限 */
}

/**
 * @brief  设置积分项独立上限（抗积分饱和）
 *
 * 积分饱和（Integral Windup / 积分"卷起"）是什么？
 *   想象一个场景：你的目标是让车停在 0 米位置，
 *   但车被一块砖头挡住了，到不了 0 米。
 *   积分项看到"一直有误差"，就不断累加，越积越大。
 *   砖头移开时，积分项已经累积了很大的值，
 *   导致车猛冲过目标，再花很长时间才能"消化"掉积分。
 *   这个过程就叫"积分饱和"。
 *
 * 抗积分饱和（Anti-windup / 抗"卷起"）就是限制积分项的最大值。
 * i_max 就是这个"积分帽"——积分项不能超过这个值。
 *
 * i_max 的设置规则：
 *   0：默认值。实际积分上限自动跟随 u_max（输出上限）。
 *      对于大多数情况，这就够了——输出都不能超过 u_max，
 *      积分也不应该超过。
 *   正数：独立设置。如果你想更严格地限制积分（比如 i_max = 500，
 *      但 u_max = 1000），传正数即可。这样积分被更早地"掐住"。
 *   负数：被强制改为 0（负数没有物理意义）。
 *
 * @param pid        PID 实例指针
 * @param i_abs_max  积分项绝对值上限（≥ 0）
 */
void pid_set_integral_limit(pid_t *pid, float i_abs_max)
{
    if (pid == NULL) return;     /* NULL 检查 */

    /* 如果传入了负数，强制改为 0。
     * 因为"负的上限"没有意义——积分上限应该是正数（或 0）。
     * 这是"宽容性设计"：输入不合理 → 自动修正为合理值。 */
    if (i_abs_max < 0.0f) i_abs_max = 0.0f;

    pid->i_max = i_abs_max;      /* 设置积分上限 */
}

/**
 * @brief  设置微分项 EMA 低通滤波系数
 *
 * 微分项（D 项）的问题是：它放大了测量噪声。
 * 因为微分就是"求导"——导数对微小变化特别敏感。
 * 传感器数据稍微抖动一下（比如从 1.00 跳到 1.01），
 * 导数就可能从 0 变成很大的值，导致电机输出剧烈波动。
 *
 * EMA（指数移动平均）滤波就是来"压平"这些毛刺的。
 * 公式：d_filt = alpha × d_new + (1 - alpha) × d_prev
 *
 * 参数 alpha 的含义：
 *   0.0：禁用滤波（"裸 D"）
 *       d_filt = d_new，完全不用历史值。
 *       适合传感器数据已经很干净的情况。
 *   0.1：强滤波
 *       d_filt = 0.1×新值 + 0.9×历史值。
 *       新值只占 10%，大部分是历史值，输出非常平滑。
 *   0.5：中等滤波
 *       d_filt = 0.5×新值 + 0.5×历史值。
 *       新值和历史值各占一半，折中。
 *   1.0：无滤波
 *       d_filt = 1.0×新值 + 0×历史值 = d_new。
 *       等同禁用滤波，但不如直接用 0.0 清晰。
 *
 * @param pid    PID 实例指针
 * @param alpha  滤波系数 [0, 1]，超出范围会被自动钳位
 */
void pid_set_d_filter(pid_t *pid, float alpha)
{
    if (pid == NULL) return;     /* NULL 检查 */

    /* 钳位 alpha 到 [0, 1] 范围内
     * alpha < 0 → 改为 0
     * alpha > 1 → 改为 1
     * 这保证了滤波系数的合法性。
     * 如果 alpha = -0.5，滤波公式会产生"负权重"，不合理。
     * 如果 alpha = 2.0，滤波会过度放大新值，也不合理。 */
    if (alpha < 0.0f) alpha = 0.0f;   /* 低于下限 → 钳到 0 */
    if (alpha > 1.0f) alpha = 1.0f;   /* 高于上限 → 钳到 1 */

    pid->d_filter_alpha = alpha;       /* 设置滤波系数 */
}

/**
 * @brief  复位 PID 内部状态（清空积分和微分历史）
 *
 * 这个函数"重置"了 PID 的"记忆"——让它忘记过去。
 * 但"忘记"的是运行时状态（积分值、上一拍测量值等），
 * 不是配置参数（Kp/Ki/Kd、限幅值等）。
 *
 * 什么时候需要复位？
 *   1. 切换目标值（setpoint）时
 *      比如从"原地平衡（目标 0°）"切换到"前进 10°（目标 10°）"
 *      旧的积分累积针对 0°，到了 10° 误差方向变了，旧积分有害
 *   2. PID 长时间未使用后重新启用
 *      控制暂停了一段时间，历史数据已经过时了
 *   3. 调试阶段切换参数
 *      改了 Kp 之后，旧积分是之前环境下的，需要清掉重新来
 *   4. 从"手动控制"切换到"自动控制"时
 *      手动控制期间 PID 没运行，历史数据无效
 *
 * 复位保留什么？保留不保留什么？
 *   ✅ 保留：Kp, Ki, Kd, u_min, u_max, i_max, d_filter_alpha
 *   ❌ 清零：i_term, prev_meas, prev_d_filt, has_prev
 *
 * @param pid  PID 实例指针
 */
void pid_reset(pid_t *pid)
{
    if (pid == NULL) return;     /* NULL 检查 */

    /* ---- 以下四项是 PID 的"运行记忆"，全部清零 ---- */
    pid->i_term      = 0.0f;   /* 积分累积值清零：忘掉过去的累积误差 */
    pid->prev_meas   = 0.0f;   /* 上一拍测量值清零：忘掉上一次的测量值 */
    pid->prev_d_filt = 0.0f;   /* 上一拍滤波值清零：忘掉上一次的微分历史 */
    pid->has_prev    = false;  /* 首拍标志复位：表明"没有历史数据，下一拍是第一次"
                                * 这样 pid_step() 在下一拍会跳过微分计算，
                                * 只记录测量值，等待再下一拍才开始正常运算。 */
}

/* ============================================================
 * 核心计算函数 pid_step ⭐
 * ============================================================
 * 这是整个 PID 模块最关键的函数——每次调用完成一次完整的 PID 控制计算。
 *
 * pid_step 的名字含义：
 *   pid = PID 控制器
 *   step = 执行一步（一次迭代）
 *
 * 应该在控制循环中每拍调用一次，每次传入：
 *   - target：当前的目标值（比如"我要 0° 直立"）
 *   - measured：当前的测量值（比如"现在 2.5° 前倾"）
 *   - dt_sec：距上一拍的时间（比如 5 ms = 0.005 秒）
 *
 * 调用频率的建议：
 *   自平衡小车建议 100~500 Hz（每 10~2 ms 一次）。
 *   太低（<50 Hz）：控制延迟太大，小车稳不住。
 *   太高（>1000 Hz）：CPU 负担重，但收益递减（传感器和电机响应速度有限）。
 *
 * 函数内部的计算步骤（共 10 步）：
 *   第 1 步：安全检查（NULL 指针、非法 dt）
 *   第 2 步：计算误差 error = target - measured
 *   第 3 步：比例项 p_term = Kp × error
 *   第 4 步：积分增量和试探 i_inc = Ki × error × dt, i_try = i_term + i_inc
 *   第 5 步：积分钳位 i_clamped = clamp(i_try, -i_max, +i_max)
 *   第 6 步：微分计算 d_meas = (measured - prev_meas) / dt
 *   第 7 步：微分滤波 d_filt = α × d_meas + (1-α) × prev_d_filt
 *   第 8 步：三项合成 u_raw = p_term + i_clamped + d_term
 *   第 9 步：输出限幅 u = clamp(u_raw, u_min, u_max)
 *   第 10 步：抗积分饱和——判断是否撤回本拍的积分增量
 *
 * @param pid        PID 实例指针
 * @param target     目标值（setpoint）
 * @param measured   测量值（反馈值）
 * @param dt_sec     距上一拍的时间（秒）
 * @return float     控制量输出，范围 [u_min, u_max]
 */
float pid_step(pid_t *pid, float target, float measured, float dt_sec)
{
    /* ================================================================
     * 第 1 步：安全检查
     * ================================================================
     * 两个检查，缺一不可：
     *
     * 检查 1：pid 是否为 NULL？
     *   如果为 NULL，返回 0.0 而不是试图访问 pid->kp（会崩溃）。
     *   这是底线防御——不管调用方怎么乱传参，函数不能崩溃。
     *
     * 检查 2：dt_sec 是否合法？
     *   如果 dt_sec <= 0，说明传入的时间间隔非法。
     *   为什么 dt_sec = 0 也不行？因为后面有 d_meas = (Δmeasured) / dt，
     *   如果 dt = 0，除以零会导致无穷大（NaN），彻底破坏计算。
     *   返回 0.0 是安全的选择——输出为 0，电机不动。
     */
    if (pid == NULL) return 0.0f;
    if (dt_sec <= 0.0f) return 0.0f;

    /* ================================================================
     * 第 2 步：计算误差 error
     * ================================================================
     * error = target - measured
     *
     * 这是 PID 控制的"输入信号"——它告诉控制器：目标偏离了多少？
     *
     * 例子：
     *   target = 0°（我要直立），measured = 2.5°（现在前倾了 2.5°）
     *   error = 0 - 2.5 = -2.5°（误差为负，说明车体向前倾了）
     *
     * 正负约定：
     *   error > 0：measured < target，需要正向出力
     *   error < 0：measured > target，需要反向出力
     *   error = 0：perfect！目标达到了
     *
     * 注意：error 是有单位的！用角度传进来的，error 就是角度。
     * Kp 的单位就是"输出/角度"——每偏差 1°，输出多少控制量。
     */
    float error = target - measured;

    /* ================================================================
     * 第 3 步：比例项 P
     * ================================================================
     * p_term = Kp × error
     *
     * 比例项是 PID 中最直观的部分——误差越大，输出越大。
     * 就像一个弹簧：拉得越远，弹回来的力越大。
     *
     * 例子：
     *   Kp = 1.5, error = -2.5°
     *   p_term = 1.5 × (-2.5) = -3.75
     *   含义：输出 -3.75 的力（负值=向后推）来纠正前倾。
     *
     * 只有 P 项时的问题：
     *   系统会来回震荡——因为 P 项只看"现在偏了多少"，
     *   不知道"现在倒得有多快"，所以经常纠正过头再纠正回来。
     *   这就是为什么需要 D 项来"刹车"。 */
    float p_term = pid->kp * error;

    /* ================================================================
     * 第 4 步：积分项 I —— 增量计算和试探累加
     * ================================================================
     * i_inc  = Ki × error × dt    ← 本拍应该增加多少积分
     * i_try  = i_term + i_inc     ← 先"试探性"累加（可能被撤回）
     *
     * 为什么要乘以 dt？
     *   积分是"时间的累积"——dt 越大（控制周期越长），每拍的积分增量就越大。
     *   如果不乘 dt，同样的 Ki 在不同控制频率下效果完全不同。
     *   乘了 dt 之后，Ki 的量纲变成"1/秒"，使其与频率无关。
     *
     * 为什么要"试探"而不直接更新？
     *   因为后面还要做抗饱和判断——如果输出饱和了，可能要把这个增量撤回。
     *   所以先用 i_try 存下来，不急着写到 pid->i_term 里。 */
    float i_inc      = pid->ki * error * dt_sec;
    float i_try      = pid->i_term + i_inc;

    /* ================================================================
     * 第 5 步：积分项 I —— 钳位（抗积分饱和的核心）
     * ================================================================
     * 把试探后的积分值 i_try 限制在 [-i_abs_max, +i_abs_max] 范围内。
     *
     * i_max = 0 的特殊处理：
     *   如果用户没设置 i_max（默认 0），则积分上限自动等于输出上限 u_max。
     *   这意味着"积分不可以比输出更猛"——是一个合理的默认。
     *
     * 为什么需要 i_abs_min = -i_abs_max？
     *   因为积分可以是正的（要正向出力），也可以是负的（要反向出力）。
     *   正负是对称的，所以下限就是上限的相反数。 */
    float i_abs_max  = (pid->i_max > 0.0f) ? pid->i_max : pid->u_max;
    float i_abs_min  = -i_abs_max;
    float i_clamped  = clampf(i_try, i_abs_min, i_abs_max);

    /* ================================================================
     * 第 6 ~ 7 步：微分项 D（on measurement + EMA 滤波）
     * ================================================================
     *
     * 步骤 6：计算微分 d_meas = (measured - prev_meas) / dt
     *   含义：测量值的变化率——"车体正在以多快的速度倾斜"。
     *   注意：这里的微分是对"测量值"求导，不是对"误差"求导！
     *   这是"d on measurement"（微分作用于测量值）的实现。
     *
     *   为什么对测量值而非误差求导？
     *     假设你把目标从 0° 突然改成 10°，误差从 0 跳变到 -10。
     *     如果对误差求导：d(error)/dt 瞬间 = 无穷大 → D 项尖峰 → 电机猛冲。
     *     如果对测量值求导：d(measured)/dt 不变（车体还没动呢）→ 平滑过渡。
     *
     * 步骤 7：EMA 滤波（可选）
     *   如果 d_filter_alpha > 0，对微分值做指数移动平均滤波。
     *   d_filt = alpha × d_meas + (1-alpha) × prev_d_filt
     *
     *   为什么要滤波？
     *     传感器测量值总有噪声（如 2.50, 2.51, 2.49, 2.50...），
     *     这些微小抖动在求导后可能被放大 100 倍（因为除以 dt）。
     *     滤波可以"压平"这些噪声，让微分项输出更平滑。
     *
     * 首拍特殊处理：
     *   第一次调用时，has_prev = false，还没有历史测量值。
     *   此时微分无法计算（不知道"变化"了多少），
     *   所以只记录当前测量值并设 has_prev = true，跳过微分计算。
     *   下一拍开始，就有 prev_meas 可以用了。
     */
    float d_term = 0.0f;  /* 微分项输出，初始化为 0 */

    if (pid->has_prev) {
        /* ★ 第 6 步：计算微分（对测量值求导）
         * d_meas 的单位 = 测量值单位 / 秒
         * 例如测量值是角度（°），dt 是秒（s），
         * 则 d_meas 的单位是 °/s（度每秒）。
         * 这刚好和陀螺仪输出的角速度单位一致！ */
        float d_meas = (measured - pid->prev_meas) / dt_sec;

        /* ★ 第 7 步：EMA 低通滤波
         * 如果 alpha > 0：执行滤波
         * 如果 alpha <= 0：跳过滤波（原值直通）
         * 注意：这个三元运算符中，alpha > 0 条件隐含了"滤波开启"。
         * 当 alpha = 0 时，第二分支 d_filt = d_meas，等同于无滤波。
         * 
         * 为什么要用三元运算符而不是 if-else？
         *   因为这是一个简单的"二选一"赋值，一行写完更简洁。 */
        float a      = pid->d_filter_alpha;
        float d_filt = (a > 0.0f)
            ? (a * d_meas + (1.0f - a) * pid->prev_d_filt)  /* 有滤波 */
            : d_meas;                                          /* 无滤波 */

        /* 微分项输出 = -Kd × 滤波后的微分值
         * ⚠️ 注意负号！
         *   因为当 measured 增大时（车体前倾），我们需要反向力来刹车。
         *   所以微分项为负，与 P 项方向一致，共同对抗前倾。
         *   如果忘了负号，D 项会变成"推波助澜"——车倒得越快，越往前推。 */
        d_term            = -pid->kd * d_filt;

        /* 保存滤波后的值，供下一拍使用 */
        pid->prev_d_filt  = d_filt;
    } else {
        /* ★ 首拍特殊处理：
         *   没有历史数据，不计算微分项。
         *   只设置 has_prev = true，记录当前测量值。
         *   下一拍开始，微分计算才能正常进行。 */
        pid->has_prev    = true;     /* 标记"已有历史数据" */
        pid->prev_d_filt = 0.0f;     /* 初始滤波值 = 0 */
    }

    /* ★ 保存当前测量值作为下一拍的"上一拍测量值"
     *   这行代码在 has_prev 分支之外，无论是否首拍都会执行。
     *   所以 prev_meas 始终记录"最近一次的测量值"。 */
    pid->prev_meas = measured;

    /* ================================================================
     * 第 8 步：三项合成
     * ================================================================
     * u_raw = p_term + i_clamped + d_term
     *
     * 这里用的是 i_clamped（钳位后的积分值），而不是原始的 i_term。
     * 因为积分已经被限幅了，不会出现"积分爆炸"的问题。
     *
     * 注意：这里还没有做输出限幅，u_raw 可能会超出 [u_min, u_max]。
     * 保存 u_raw 是为了在第 10 步判断"是否饱和"。
     */
    float u_raw = p_term + i_clamped + d_term;

    /* ================================================================
     * 第 9 步：输出限幅
     * ================================================================
     * u = clamp(u_raw, u_min, u_max)
     *
     * 把输出值限制在物理可行范围内。
     * 比如电机 PWM 最大 1000，那输出就不能超过 1000。
     * 限幅之后，u 永远在 [u_min, u_max] 之间。
     */
    float u     = clampf(u_raw, pid->u_min, pid->u_max);

    /* ================================================================
     * 第 10 步：抗积分饱和（Anti-windup）
     * ================================================================
     *
     * 这是位置式 PID 中最精妙的设计之一。
     *
     * 核心思想：如果输出已经饱和（被限幅卡住了），
     * 但积分还在朝"饱和方向"累加，就不让积分继续涨。
     *
     * 饱和判断逻辑：
     *   saturated_high = 输出卡在上限 + 原始值 >= 上限
     *   saturated_low  = 输出卡在下限 + 原始值 <= 下限
     *
     * 为什么既要检查 u 又要检查 u_raw？
     *   只检查 u >= u_max 不够——u 是已经限幅过的值，它总是 <= u_max。
     *   需要 u_raw >= u_max 才能确定"本真的输出想要超过上限"。
     *   两个条件同时成立 → 真的饱和了。
     *
     * 积分撤回判断：
     *   saturated_high && i_inc > 0：上限饱和 + 积分还想往上加 → 撤回
     *   saturated_low  && i_inc < 0：下限饱和 + 积分还想往下加 → 撤回
     *
     * 通俗理解：
     *   如果油门已经踩到底了，你就别再使劲踩了，没用的。
     *   等路面变平了（误差方向反转），再松开油门。 */
    bool saturated_high = (u >= pid->u_max) && (u_raw >= pid->u_max);
    bool saturated_low  = (u <= pid->u_min) && (u_raw <= pid->u_min);

    /* 积分撤回决策 */
    if ((saturated_high && i_inc > 0.0f) ||
        (saturated_low  && i_inc < 0.0f)) {
        /* ✅ 撤回：不更新 i_term，保持上一拍的值不变
         * 这里故意不写任何语句——因为撤回就是"什么都不做"。
         * 空的 if 分支可能会有编译器警告（如 Keil 的 Warning #111），
         * 但这里没有写分号或花括号之外的内容，所以一般不会触发。
         * 有些编译器可能会建议加个 (void)0; 来消除警告。 */
    } else {
        /* ✅ 正常更新：把钳位后的积分值写入 i_term
         * 注意这里写的是 i_clamped（已限幅）而不是 i_try（原始值）。
         * 这样即使积分没有饱和，写入的也是已经限幅过的安全值。 */
        pid->i_term = i_clamped;
    }

    /* 返回控制量输出
     * u 已经在 [u_min, u_max] 范围内，调用方可以直接使用。
     * 对于自平衡小车，调用方（app_balance.c）把这个值映射为电机 PWM。 */
    return u;
}
